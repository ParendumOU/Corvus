class FakeEvent {
  constructor(readonly type: string) {}
}

interface Spec {
  tag?: 'INPUT' | 'SELECT' | 'TEXTAREA';
  type?: string;
  name?: string;
  autocomplete?: string;
  label?: string;
  value?: string;
  hidden?: boolean;
  options?: { value: string; text: string }[];
  placeholder?: string;
  maxlength?: string;
  /** Where the field is drawn, in its window's viewport (default 10,10 and 100x20). */
  rect?: { left?: number; top?: number; width?: number; height?: number };
  opacity?: string;
  /** An element around the field, with its own opacity. */
  parent?: { opacity: string; parentElement: null };
}

type Field = ReturnType<typeof field>;

function field(spec: Spec) {
  const { left = 10, top = 10, width = 100, height = 20 } = spec.hidden ? { left: 0, top: 0, width: 0, height: 0 } : (spec.rect ?? {});
  const attrs: Record<string, string> = { type: spec.type ?? (spec.tag && spec.tag !== 'INPUT' ? '' : 'text'), autocomplete: spec.autocomplete ?? '', placeholder: spec.placeholder ?? '', maxlength: spec.maxlength ?? '' };
  const el = {
    tagName: spec.tag ?? 'INPUT',
    name: spec.name ?? '',
    id: '',
    value: spec.value ?? '',
    selectedIndex: spec.options ? 0 : -1,
    options: spec.options,
    labels: spec.label ? [{ textContent: spec.label }] : [],
    form: null as unknown,
    ownerDocument: null as unknown,
    contentDocument: null as unknown,
    parentElement: spec.parent ?? null,
    opacity: spec.opacity ?? '1',
    events: [] as string[],
    getAttribute: (name: string) => attrs[name] || null,
    getBoundingClientRect: () => ({ left, top, width, height, right: left + width, bottom: top + height }),
    querySelectorAll: () => [],
    dispatchEvent(e: FakeEvent) {
      el.events.push(e.type);
      return true;
    },
  };
  return el;
}

function page(origin: string, forms: Field[][], loose: Field[] = [], active: Field | null = null) {
  const win = {
    location: { origin },
    document: null as unknown,
    innerWidth: 400,
    scrollX: 0,
    scrollY: 0,
    frameElement: null as Field | null,
    getComputedStyle: (el: { opacity: string }) => ({ visibility: 'visible', opacity: el.opacity }),
    Event: FakeEvent,
    HTMLInputElement: { prototype: {} },
    HTMLSelectElement: { prototype: {} },
    HTMLTextAreaElement: { prototype: {} },
  };
  const all = [...forms.flat(), ...loose];
  const formEls = forms.map((fields) => ({ querySelectorAll: () => fields }));
  const frames: Field[] = [];
  const doc = {
    activeElement: active,
    defaultView: win,
    frames,
    getElementById: () => null,
    querySelectorAll: (sel: string) => (sel === 'form' ? formEls : sel === 'iframe, frame' ? frames : all),
  };
  forms.forEach((fields, i) => fields.forEach((f) => (f.form = formEls[i])));
  for (const f of all) f.ownerDocument = doc;
  win.document = doc;
  return win;
}

/** Puts the page `inner` in a frame of the same site in `outer`, the frame element drawn as `spec` says. */
function frameIn(outer: ReturnType<typeof page>, inner: ReturnType<typeof page>, spec: Spec = {}): void {
  const frame = field(spec);
  frame.ownerDocument = outer.document;
  frame.contentDocument = inner.document;
  inner.frameElement = frame;
  (outer.document as { frames: Field[] }).frames.push(frame);
}

/** Runs the script exactly as the phone injects it. */
function run(win: unknown, address = ADDRESS, origin = 'https://shop.example'): number {
  return evaluate(win, fillAddressScript(address, origin));
}

function evaluate(win: unknown, script: string): number {
  return new Function('window', `return ${script};`)(win) as number;
}

describe('address fill script', () => {
  it('ships the desktop kits and the page fill as they are now', () => {
    const hint = 'run: docker compose run --rm dev sh -c "cd apps/mobile && UPDATE_FORM_FILL=1 pnpm vitest run test/form-fill.test.ts"';
    for (const [name, source] of Object.entries(SOURCES)) expect(shipped[name as keyof typeof shipped], `${name}: ${hint}`).toBe(source);
  });

  it('fills the empty fields of the address form, as the desktop would', () => {
    const given = field({ autocomplete: 'given-name' });
    const family = field({ autocomplete: 'family-name' });
    const line1 = field({ name: 'address1', label: 'Dirección' });
    const line2 = field({ name: 'address2', label: 'Piso, puerta' });
    const postal = field({ label: 'Código postal', value: '15001' });
    const city = field({ label: 'Ciudad' });
    const country = field({ tag: 'SELECT', name: 'country', options: [{ value: '', text: 'Elige' }, { value: 'FR', text: 'Francia' }, { value: 'ESP', text: 'España' }] });
    const email = field({ type: 'email', name: 'email' });
    const hidden = field({ name: 'phone', hidden: true });
    const win = page('https://shop.example', [[given, family, line1, line2, postal, city, country, email, hidden]]);

    expect(run(win)).toBe(7);
    expect([given.value, family.value, line1.value, line2.value, postal.value, city.value, country.value, email.value, hidden.value]).toEqual([
      'Ana',
      'Pérez García',
      'Calle Mayor 1',
      'Piso 2',
      '15001',
      'Ourense',
      'ESP',
      'ana@example.com',
      '',
    ]);
    expect(given.events).toEqual(['input', 'change']);
    expect(postal.events).toEqual([]);
  });

  it('picks the focused field’s form, else the first address form, else the page', () => {
    const login = [field({ type: 'email', autocomplete: 'email' }), field({ type: 'password' })];
    const ship = [field({ autocomplete: 'name' }), field({ autocomplete: 'street-address' }), field({ autocomplete: 'postal-code' })];
    const bill = [field({ autocomplete: 'name' }), field({ autocomplete: 'street-address' }), field({ autocomplete: 'postal-code' })];
    run(page('https://shop.example', [login, ship, bill]));
    expect(login[0]!.value).toBe('');
    expect(ship.map((f) => f.value)).toEqual(['Ana Pérez García', 'Calle Mayor 1, Piso 2', '32001']);
    expect(bill[0]!.value).toBe('');

    const ship2 = ship.map(() => field({}));
    ship2.forEach((f, i) => Object.assign(f, { getAttribute: ship[i]!.getAttribute }));
    const bill2 = [field({ autocomplete: 'name' }), field({ autocomplete: 'street-address' }), field({ autocomplete: 'postal-code' })];
    expect(run(page('https://shop.example', [ship2, bill2], [], bill2[1]!))).toBe(3);
    expect(ship2[0]!.value).toBe('');
    expect(bill2[0]!.value).toBe('Ana Pérez García');

    const loose = [field({ autocomplete: 'name' }), field({ autocomplete: 'postal-code' }), field({ autocomplete: 'address-level2' })];
    expect(run(page('https://shop.example', [], loose))).toBe(3);
    expect(loose[2]!.value).toBe('Ourense');
  });

  it('leaves alone the fields the person cannot see, but not the one they are in', () => {
    const shown = () => [field({ autocomplete: 'name' }), field({ autocomplete: 'street-address' }), field({ autocomplete: 'postal-code' })];
    const hidden = [
      field({ autocomplete: 'tel', opacity: '0' }),
      field({ autocomplete: 'email', parent: { opacity: '0.05', parentElement: null } }),
      field({ autocomplete: 'address-level2', rect: { width: 1, height: 1 } }),
      field({ autocomplete: 'address-level1', rect: { left: -500 } }),
      field({ autocomplete: 'country-name', rect: { top: -500 } }),
      field({ autocomplete: 'tel-national', rect: { left: 400 } }),
    ];
    expect(run(page('https://shop.example', [[...shown(), ...hidden]]))).toBe(3);
    expect(hidden.map((f) => [f.value, f.events.length])).toEqual(hidden.map(() => ['', 0]));

    // Above the screen but on the page: scrolled past, so seen.
    const above = field({ autocomplete: 'tel', rect: { top: -500 } });
    const scrolled = page('https://shop.example', [[...shown(), above]]);
    scrolled.scrollY = 600;
    expect(run(scrolled)).toBe(4);
    expect(above.value).toBe('600000000');

    const focused = field({ autocomplete: 'tel', opacity: '0' });
    expect(run(page('https://shop.example', [[...shown(), focused]], [], focused))).toBe(4);
    expect(focused.value).toBe('600000000');
  });

  it('looks at the frames around a field too', () => {
    const fields = () => [field({ autocomplete: 'name' }), field({ autocomplete: 'street-address' }), field({ autocomplete: 'postal-code' })];
    const inFrame = fields();
    const top = page('https://shop.example', []);
    frameIn(top, page('https://shop.example', [inFrame]));
    expect(run(top)).toBe(3);
    expect(inFrame[0]!.value).toBe('Ana Pérez García');

    for (const frame of [{ opacity: '0' }, { rect: { width: 1, height: 1 } }, { rect: { left: -500 } }] satisfies Spec[]) {
      const inHidden = fields();
      const outer = page('https://shop.example', []);
      frameIn(outer, page('https://shop.example', [inHidden]), frame);
      expect(run(outer), JSON.stringify(frame)).toBe(0);
      expect(inHidden.map((f) => f.value)).toEqual(['', '', '']);
    }
  });

  it('fills nothing without an address form, or once the page is another site', () => {
    const login = [field({ type: 'email', autocomplete: 'email' }), field({ type: 'password' })];
    expect(run(page('https://shop.example', [login]))).toBe(0);
    const ship = [field({ autocomplete: 'name' }), field({ autocomplete: 'street-address' }), field({ autocomplete: 'postal-code' })];
    expect(run(page('https://evil.example', [ship]))).toBe(-1);
    expect(ship[0]!.value).toBe('');
  });

  it('runs the same logic as the function it was made from', () => {
    const ship = [field({ autocomplete: 'name' }), field({ autocomplete: 'street-address' }), field({ autocomplete: 'postal-code' })];
    expect(fillFormInPage(addressAdapter(addressKit as never, ADDRESS), 'https://shop.example', page('https://shop.example', [ship]) as never)).toBe(3);
  });

  it('knows a web page’s origin', () => {
    expect(pageOrigin('https://shop.example/cart?x=1')).toBe('https://shop.example');
    expect(pageOrigin('http://192.168.0.10:8080/')).toBe('http://192.168.0.10:8080');
    expect(pageOrigin('about:blank')).toBe('');
    expect(pageOrigin('not a url')).toBe('');
  });
});

const CARD: CardFields = { label: 'Work', nameOnCard: 'Ana Pérez', number: '4111111111111111', expMonth: '08', expYear: '2028' };

describe('card fill script', () => {
  const cardForm = () => [
    field({ autocomplete: 'cc-number' }),
    field({ autocomplete: 'cc-name' }),
    field({ name: 'exp', placeholder: 'MM / YY' }),
    field({ autocomplete: 'cc-csc' }),
  ];

  it('fills number, name, expiry and the CVV typed in Corvus', () => {
    const fields = cardForm();
    expect(evaluate(page('https://shop.example', [fields]), fillCardScript(CARD, '123', 'https://shop.example'))).toBe(4);
    expect(fields.map((f) => f.value)).toEqual(['4111111111111111', 'Ana Pérez', '08/28', '123']);
  });

  it('takes month and year selects, and leaves typed fields and a bad CVV alone', () => {
    const month = field({ tag: 'SELECT', autocomplete: 'cc-exp-month', options: [{ value: '', text: 'MM' }, { value: '8', text: 'Agosto' }] });
    const year = field({ tag: 'SELECT', autocomplete: 'cc-exp-year', options: [{ value: '', text: 'AAAA' }, { value: '28', text: '2028' }] });
    const number = field({ autocomplete: 'cc-number', value: '5500 0000 0000 0004' });
    const csc = field({ autocomplete: 'cc-csc' });
    expect(evaluate(page('https://shop.example', [[number, month, year, csc]]), fillCardScript(CARD, '12a', 'https://shop.example'))).toBe(2);
    expect([number.value, month.value, year.value, csc.value]).toEqual(['5500 0000 0000 0004', '8', '28', '']);
  });

  it('never writes the card into a field the person cannot see', () => {
    const fields = cardForm();
    fields[3]!.opacity = '0';
    const extra = field({ autocomplete: 'cc-number', rect: { left: -500 } });
    expect(evaluate(page('https://shop.example', [[...fields, extra]]), fillCardScript(CARD, '123', 'https://shop.example'))).toBe(3);
    expect([fields[3]!.value, extra.value]).toEqual(['', '']);
  });

  it('skips the address form for the card form, and refuses another site', () => {
    const ship = [field({ autocomplete: 'name' }), field({ autocomplete: 'street-address' }), field({ autocomplete: 'postal-code' })];
    const pay = cardForm();
    expect(evaluate(page('https://shop.example', [ship, pay]), fillCardScript(CARD, '1234', 'https://shop.example'))).toBe(4);
    expect(ship[0]!.value).toBe('');
    expect(pay[3]!.value).toBe('1234');
    const other = cardForm();
    expect(evaluate(page('https://evil.example', [other]), fillCardScript(CARD, '123', 'https://shop.example'))).toBe(-1);
    expect(other[0]!.value).toBe('');
    expect(evaluate(page('https://shop.example', [ship.map(() => field({}))]), fillCardScript(CARD, '123', 'https://shop.example'))).toBe(0);
  });

  it('runs the same logic as the functions it was made from', () => {
    const fields = cardForm();
    expect(fillFormInPage(cardAdapter(cardKit as never, CARD, '999'), 'https://shop.example', page('https://shop.example', [fields]) as never)).toBe(4);
  });

  it('is offered on https pages and on http pages of the phone itself only', () => {
    const allowed = ['https://shop.example', 'https://shop.example:8443', 'http://localhost:3000', 'http://127.0.0.1', 'http://[::1]:8080'];
    const refused = ['http://shop.example', 'http://192.168.0.10:8080', 'http://localhost.shop.example', 'http://127.0.0.2', 'http://[::2]', 'ftp://localhost', '', 'not a url'];
    expect(allowed.filter(cardFillAllowed)).toEqual(allowed);
    expect(refused.filter(cardFillAllowed)).toEqual([]);
    expect(cardFillAllowed(pageOrigin('http://[::1]:8080/pay'))).toBe(true);
  });
});
